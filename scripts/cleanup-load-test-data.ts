import path from 'path';
import { PrismaClient } from '@prisma/client';
import { PrismaPg } from '@prisma/adapter-pg';
import { Redis } from '@upstash/redis';
import dotenv from 'dotenv';

process.env.NODE_TLS_REJECT_UNAUTHORIZED = '0';

dotenv.config({ path: path.resolve(__dirname, '../apps/backend/.env') });

let connectionUrl = process.env.DATABASE_URL || process.env.DIRECT_URL || '';
if (connectionUrl.includes('sslmode=require') || connectionUrl.includes('sslmode=prefer')) {
  connectionUrl = connectionUrl.replace(/sslmode=[a-z\-]+/i, 'sslmode=no-verify');
}

const adapter = new PrismaPg({ connectionString: connectionUrl });
const prisma = new PrismaClient({ adapter });

async function cleanupLoadTestData() {
  console.log('=======================================================');
  console.log('🧹 STARTING COMPREHENSIVE LOAD-TEST DATA PURGE');
  console.log('=======================================================\n');

  const report: Record<string, number> = {};

  // 1. CANCEL / DELETE ANY QUEUED OR PENDING NOTIFICATIONS & WHATSAPP LOGS
  console.log('1️⃣ Checking & Purging any queued/pending messages...');
  const pendingWaLogs = await prisma.whatsAppMessageLog.deleteMany({
    where: {
      status: { in: ['QUEUED', 'SENDING'] as any },
    },
  });
  report['WhatsApp Logs Cancelled from Queue'] = pendingWaLogs.count;
  console.log(`   ✅ Cancelled ${pendingWaLogs.count} pending/queued WhatsApp logs.`);

  const pendingNotifs = await prisma.notification.deleteMany({
    where: {
      OR: [
        { whatsappStatus: { in: ['PENDING', 'PROCESSING'] as any } },
        { pushStatus: { in: ['PENDING', 'PROCESSING'] as any } },
      ],
    },
  });
  report['Notifications Cancelled from Queue'] = pendingNotifs.count;
  console.log(`   ✅ Cancelled ${pendingNotifs.count} pending/processing notifications.`);

  // 2. DELETE TEST WHATSAPP MESSAGE LOGS GENERATED DURING LOAD TEST
  console.log('\n2️⃣ Purging WhatsApp message logs created during load test...');
  const testWaLogs = await prisma.whatsAppMessageLog.deleteMany({
    where: {
      createdAt: { gte: new Date('2026-10-17T15:00:00Z') },
      templateType: { in: ['EXAM_FAILED_ALERT_PARENT', 'EXAM_PASSED_ALERT_PARENT', 'GENERAL_ANNOUNCEMENT'] },
      OR: [
        { messageBody: { contains: 'اختبار النحو' } },
        { messageBody: { contains: 'تأخير متكرر' } },
        { messageBody: { contains: 'درجات الاختبار' } },
        { messageBody: { contains: 'نتيجة الاختبار' } },
      ],
    },
  });
  report['Test WhatsApp Message Logs Deleted'] = testWaLogs.count;
  console.log(`   ✅ Deleted ${testWaLogs.count} test WhatsApp message logs.`);

  // 3. DELETE NOTIFICATIONS GENERATED DURING LOAD TEST
  console.log('\n3️⃣ Purging in-app and parent notifications generated during load test...');
  const testNotifs = await prisma.notification.deleteMany({
    where: {
      OR: [
        { referenceEntityId: '8238fc55-01cc-4e3e-9cc5-f450d3372e79' },
        {
          createdAt: { gte: new Date('2026-10-17T15:00:00Z') },
          type: { in: ['EXAM_FAILED_ALERT_PARENT', 'EXAM_PASSED_ALERT_PARENT', 'ASSESSMENT_GRADED', 'REPEATED_LATENESS_PARENT', 'PAYMENT_RECEIVED_PARENT'] },
        },
        {
          createdAt: { gte: new Date('2026-10-17T15:00:00Z') },
          type: 'WEBSITE_INQUIRY',
        },
      ],
    },
  });
  report['Test Notifications Deleted'] = testNotifs.count;
  console.log(`   ✅ Deleted ${testNotifs.count} test notifications.`);

  // 4. DELETE TEST WEBSITE CONTACT MESSAGES (557 messages)
  console.log('\n4️⃣ Purging website contact messages generated by load test...');
  const testContacts = await prisma.contactMessage.deleteMany({
    where: {
      OR: [
        { name: { startsWith: 'زائر تجريبي' } },
        { message: { contains: 'استفسار عن اشتراكات السنتر ومواعيد امتحانات الثانوية العامة' } },
      ],
    },
  });
  report['Test Contact Messages Deleted'] = testContacts.count;
  console.log(`   ✅ Deleted ${testContacts.count} test contact messages.`);

  // 5. DELETE TEST ASSESSMENT SUBMISSIONS & ANSWERS
  console.log('\n5️⃣ Purging test assessment submissions, answers and exam...');
  const testAssessments = await prisma.assessment.findMany({
    where: {
      OR: [
        { id: '8238fc55-01cc-4e3e-9cc5-f450d3372e79' },
        { title: { contains: 'اختبار النحو والبلاغة التفاعلي - قياس القدرات' } },
      ],
    },
    select: { id: true, title: true },
  });

  let totalAnswersDeleted = 0;
  let totalSubmissionsDeleted = 0;
  let totalQuestionsDeleted = 0;
  let totalAssessmentsDeleted = 0;

  for (const a of testAssessments) {
    const answersDel = await prisma.studentAnswer.deleteMany({
      where: { submission: { assessmentId: a.id } },
    });
    totalAnswersDeleted += answersDel.count;

    const subsDel = await prisma.assessmentSubmission.deleteMany({
      where: { assessmentId: a.id },
    });
    totalSubmissionsDeleted += subsDel.count;

    const qDel = await prisma.assessmentQuestion.deleteMany({
      where: { assessmentId: a.id },
    });
    totalQuestionsDeleted += qDel.count;

    await prisma.assessment.delete({
      where: { id: a.id },
    });
    totalAssessmentsDeleted++;
  }
  report['Test Student Answers Deleted'] = totalAnswersDeleted;
  report['Test Assessment Submissions Deleted'] = totalSubmissionsDeleted;
  report['Test Assessment Questions Deleted'] = totalQuestionsDeleted;
  report['Test Assessments Deleted'] = totalAssessmentsDeleted;
  console.log(`   ✅ Deleted ${totalAnswersDeleted} student answers.`);
  console.log(`   ✅ Deleted ${totalSubmissionsDeleted} assessment submissions.`);
  console.log(`   ✅ Deleted ${totalQuestionsDeleted} questions & ${totalAssessmentsDeleted} test assessment.`);

  // 6. DELETE TEST PAYMENTS (58 records)
  console.log('\n6️⃣ Purging test tuition payment records...');
  const testPayments = await prisma.studentPaymentRecord.deleteMany({
    where: {
      OR: [
        { notes: { contains: 'اختبار الحمل' } },
        { notes: { contains: 'فحص التحمل' } },
        { notes: { contains: 'k6' } },
      ],
    },
  });
  report['Test Payment Records Deleted'] = testPayments.count;
  console.log(`   ✅ Deleted ${testPayments.count} test payment records.`);

  // 7. DELETE TEST ATTENDANCE RECORDS (58 records from load test)
  console.log('\n7️⃣ Purging test QR attendance records...');
  const testAttendance = await prisma.attendanceRecord.deleteMany({
    where: {
      sessionId: '8ed84776-70f9-47bd-8e37-680d64cf9cc0',
      recordingMethod: 'QR_SCAN',
      recordedAt: { gte: new Date('2026-10-17T15:00:00Z') },
    },
  });
  report['Test Attendance Records Deleted'] = testAttendance.count;
  console.log(`   ✅ Deleted ${testAttendance.count} test attendance records.`);

  // 8. RESET TEST COURSE PROGRESS
  console.log('\n8️⃣ Purging simulated course video progress...');
  const testProgress = await prisma.courseProgress.deleteMany({
    where: {
      lastSyncedAt: { gte: new Date('2026-10-17T15:00:00Z') },
    },
  });
  report['Test Video Progress Records Deleted'] = testProgress.count;
  console.log(`   ✅ Deleted ${testProgress.count} simulated lesson progress records.`);

  // 9. FLUSH UPSTASH REDIS CACHE
  console.log('\n9️⃣ Flushing Redis cache...');
  const redisUrl = process.env.UPSTASH_REDIS_REST_URL;
  const redisToken = process.env.UPSTASH_REDIS_REST_TOKEN;
  if (redisUrl && redisToken) {
    try {
      const redis = new Redis({ url: redisUrl, token: redisToken });
      await redis.flushdb();
      report['Redis Cache Flushed'] = 1;
      console.log('   ✅ Upstash Redis cache successfully flushed.');
    } catch (err: any) {
      console.warn(`   ⚠️ Could not flush Redis: ${err?.message}`);
      report['Redis Cache Flushed'] = 0;
    }
  } else {
    console.log('   ℹ️ Redis not configured or running in memory fallback.');
    report['Redis Cache Flushed'] = 0;
  }

  console.log('\n=======================================================');
  console.log('🎉 PURGE COMPLETE! SUMMARY OF DELETED ITEMS:');
  console.log('=======================================================');
  for (const [key, count] of Object.entries(report)) {
    console.log(`  - ${key.padEnd(42)}: ${count}`);
  }
  console.log('=======================================================\n');

  await prisma.$disconnect();
}

cleanupLoadTestData().catch((err) => {
  console.error('❌ Cleanup failed:', err);
  process.exit(1);
});
